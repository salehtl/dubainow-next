#!/usr/bin/env python3
"""Generate design/Tokens.kt from tools/tokens.json (exported from Paper).

Paper has no modes, so tokens use suffixes: base = Light/English/iOS, then -dark, -ar, -android.
For Android we take the `-android` value when one exists, otherwise the base value (light mode).
Skipped: Apple-kit, glass-recipe (Paper-only) and Arabic tokens.

Run:  python3 tools/gen_tokens.py
"""
import json, re, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
tokens = {t["name"]: t["value"] for t in json.load(open(ROOT / "tools/tokens.json"))["tokens"]}

SKIP = ("--color-apple-", "--color-glass-", "--color-material-glass-", "--color-effect-",
        "--color-native-", "--spacing-apple-", "--spacing-effect-", "--radius-apple-")


def skip(name):
    if name.startswith(SKIP) or "-dark" in name or name.endswith("-ar") or "-ar-" in name:
        return True
    # "-android" variants are folded into their base name; Android-only tokens (no base) are kept.
    return name.endswith("-android") and name[: -len("-android")] in tokens


def base_name(name):
    return name[: -len("-android")] if name.endswith("-android") else name


def android_value(name):
    return tokens.get(name + "-android", tokens[name])


def resolve(value, seen=()):
    m = re.fullmatch(r"var\((--[\w-]+)\)", value.strip())
    if not m:
        return value.strip()
    ref = m.group(1)
    if ref in seen or ref not in tokens:
        raise ValueError(f"bad alias {value}")
    return resolve(android_value(ref), seen + (ref,))


def argb(value):
    v = value.strip()
    m = re.fullmatch(r"#([0-9A-Fa-f]{6})([0-9A-Fa-f]{2})?", v)
    if m:
        a = m.group(2) or "FF"
        return f"0x{a.upper()}{m.group(1).upper()}"
    m = re.fullmatch(r"rgba?\(\s*([\d.]+)[\s,]+([\d.]+)[\s,]+([\d.]+)\s*(?:[/,]\s*([\d.]+)(%?))?\s*\)", v)
    if m:
        a = 1.0
        if m.group(4):
            a = float(m.group(4)) / (100 if m.group(5) else 1)
        r, g, b = (int(float(m.group(i))) for i in (1, 2, 3))
        return f"0x{round(a * 255):02X}{r:02X}{g:02X}{b:02X}"
    raise ValueError(f"unparsed colour {value}")


def camel(name, prefix):
    body = name[len(prefix):]
    parts = re.split(r"[-_]", body)
    out = parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])
    return ("_" + out) if out[0].isdigit() else out


def px(value):
    v = resolve(value)
    m = re.fullmatch(r"(-?[\d.]+)(px)?", v)
    return float(m.group(1)) if m else None


lines = [
    "// GENERATED by tools/gen_tokens.py from tools/tokens.json (Paper). Do not edit by hand.",
    "// Names follow the Paper tokens: --color-surface-primary -> DNColor.surfacePrimary.",
    "// Values prefer the -android variant where Paper defines one (light mode).",
    "package com.salehtl.dubainownext.design",
    "",
    "import androidx.compose.ui.graphics.Color",
    "import androidx.compose.ui.unit.dp",
    "",
    "object DNColor {",
]
n = 0
for name in sorted(tokens):
    if not name.startswith("--color-") or skip(name):
        continue
    try:
        value = argb(resolve(android_value(name)))
    except ValueError:
        continue
    lines.append(f"    /** `{name}` */")
    lines.append(f"    val {camel(base_name(name), '--color-')} = Color({value})")
    n += 1
lines.append("}")
lines.append("")
for obj, prefix in (("DNSpace", "--spacing-"), ("DNRadius", "--radius-"), ("DNSize", "--container-")):
    lines.append(f"object {obj} {{")
    for name in sorted(tokens):
        if not name.startswith(prefix) or skip(name):
            continue
        v = px(android_value(name))
        if v is None:
            continue
        lines.append(f"    /** `{name}` */")
        lines.append(f"    val {camel(base_name(name), prefix)} = {v:g}.dp")
    lines.append("}")
    lines.append("")
out = ROOT / "app/src/main/java/com/salehtl/dubainownext/design/Tokens.kt"
out.write_text("\n".join(lines))
print(f"wrote {out} with {n} colours")
