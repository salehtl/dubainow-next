#!/usr/bin/env python3
"""Generate DesignSystem/Tokens.swift from design/tokens.json (exported from Paper).

Paper has no modes, so tokens use suffixes: base = Light/English/iOS, then -dark, -ar, -android.
This script emits iOS values only: colours as dynamic light/dark colours, plus spacing,
radius and container sizes as CGFloat constants. Apple-kit, Android, Material and the
Paper-only glass recipe tokens are skipped (iOS uses system colours and native glass).

Run:  python3 tools/gen_tokens.py
"""
import json, re, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
tokens = {t["name"]: t["value"] for t in json.load(open(ROOT / "design/tokens.json"))["tokens"]}

SKIP = ("--color-apple-", "--color-m3-", "--color-glass-", "--color-material-glass-", "--color-effect-",
        "--color-native-", "--spacing-apple-", "--spacing-effect-", "--radius-apple-")

def skip(name):
    return name.startswith(SKIP) or "-android" in name or name.endswith("-ar") or "-ar-" in name


def resolve(value, seen=()):
    m = re.fullmatch(r"var\((--[\w-]+)\)", value.strip())
    if not m:
        return value.strip()
    ref = m.group(1)
    if ref in seen or ref not in tokens:
        raise ValueError(f"bad alias {value}")
    return resolve(tokens[ref], seen + (ref,))


def rgba(value):
    v = value.strip()
    m = re.fullmatch(r"#([0-9A-Fa-f]{6})([0-9A-Fa-f]{2})?", v)
    if m:
        h = m.group(1)
        a = int(m.group(2), 16) / 255 if m.group(2) else 1.0
        return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16), a
    m = re.fullmatch(r"rgba?\(\s*([\d.]+)[\s,]+([\d.]+)[\s,]+([\d.]+)\s*(?:[/,]\s*([\d.]+)(%?))?\s*\)", v)
    if m:
        a = 1.0
        if m.group(4):
            a = float(m.group(4)) / (100 if m.group(5) else 1)
        return int(float(m.group(1))), int(float(m.group(2))), int(float(m.group(3))), a
    raise ValueError(f"unparsed colour {value}")


def camel(name, prefix):
    body = name[len(prefix):]
    parts = re.split(r"[-_]", body)
    out = parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])
    if out[0].isdigit():
        out = "_" + out
    return out


def px(value):
    v = resolve(value)
    m = re.fullmatch(r"(-?[\d.]+)(px)?", v)
    if not m:
        return None
    return float(m.group(1))


lines = [
    "// GENERATED by tools/gen_tokens.py from design/tokens.json (Paper). Do not edit by hand.",
    "// Names follow the Paper tokens: --color-surface-primary -> DNColor.surfacePrimary.",
    "import SwiftUI",
    "",
    "enum DNColor {",
]
count = 0
for name in sorted(tokens):
    if not name.startswith("--color-") or name.endswith("-dark") or skip(name):
        continue
    try:
        light = rgba(resolve(tokens[name]))
        dark_name = name + "-dark"
        dark = rgba(resolve(tokens[dark_name])) if dark_name in tokens else light
    except ValueError:
        continue
    ident = camel(name, "--color-")
    lines.append(f"    /// `{name}`")
    lines.append(
        f"    static let {ident} = Color.dn(light: ({light[0]}, {light[1]}, {light[2]}, {light[3]:.3f}), "
        f"dark: ({dark[0]}, {dark[1]}, {dark[2]}, {dark[3]:.3f}))"
    )
    count += 1
lines.append("}")
lines.append("")

for enum, prefix in (("DNSpace", "--spacing-"), ("DNRadius", "--radius-"), ("DNSize", "--container-")):
    lines.append(f"enum {enum} {{")
    for name in sorted(tokens):
        if not name.startswith(prefix) or skip(name) or name.endswith("-dark"):
            continue
        v = px(tokens[name])
        if v is None:
            continue
        lines.append(f"    /// `{name}`")
        lines.append(f"    static let {camel(name, prefix)}: CGFloat = {v:g}")
    lines.append("}")
    lines.append("")

lines += [
    "extension Color {",
    "    /// A colour with separate light and dark values (0–255 components, 0–1 alpha).",
    "    static func dn(light: (Int, Int, Int, Double), dark: (Int, Int, Int, Double)) -> Color {",
    "        Color(uiColor: UIColor { traits in",
    "            let c = traits.userInterfaceStyle == .dark ? dark : light",
    "            return UIColor(red: CGFloat(c.0) / 255, green: CGFloat(c.1) / 255, blue: CGFloat(c.2) / 255, alpha: CGFloat(c.3))",
    "        })",
    "    }",
    "}",
    "",
]
out = ROOT / "DubaiNowDemo/DesignSystem/Tokens.swift"
out.write_text("\n".join(lines))
print(f"wrote {out} with {count} colours")
